function t(k){ return (T[LANG]&&T[LANG][k])||(T.en[k])||k; }
/* String interpolation helper: tFmt('Step {n} of {total}', {n:1,total:5}) */
function tFmt(k, vars){
  let s = t(k);
  if(!vars) return s;
  Object.keys(vars).forEach(name=>{ s = s.split('{'+name+'}').join(vars[name]); });
  return s;
}
